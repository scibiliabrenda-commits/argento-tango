const SUPPORTED = ["es", "en", "pt"];
const STORAGE_KEY = "argento-lang";
let currentLang = "es";

function t(key, lang = currentLang) {
  return (translations[lang] && translations[lang][key]) ?? translations.es[key] ?? key;
}

function switchLanguage(lang) {
  if (!SUPPORTED.includes(lang)) lang = "es";
  currentLang = lang;

  document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  document.title = t("metaTitle");
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", t("metaDesc"));

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18n);
  });

  document.querySelectorAll(".lang-switch button[data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });

  try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) { /* modo privado */ }
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang } }));
}

function detectLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(saved)) return saved;
  } catch (_) {}
  const nav = (navigator.language || "es").slice(0, 2).toLowerCase();
  return SUPPORTED.includes(nav) ? nav : "es";
}

window.ArgentoI18n = { translations, t, switchLanguage, detectLanguage, get lang() { return currentLang; } };
